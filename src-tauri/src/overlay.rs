use crate::{common::workspace, rea::copy_overlay_firmware};
use serde::Serialize;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

#[derive(Debug, Clone, Serialize)]
pub struct NodeRule {
    pub path: String,
    pub mode: Option<String>,
    pub owner: Option<String>,
    pub group: Option<String>,
    pub android_owner: Option<String>,
    pub android_group: Option<String>,
    pub sources: Vec<String>,
}

#[derive(Debug, Serialize)]
pub struct OverlayReport {
    pub rules: Vec<NodeRule>,
    pub rules_text: String,
    pub sources: Vec<String>,
    pub skipped: Vec<String>,
    pub firmware_count: usize,
    pub overlay_dir: String,
    pub zip_path: String,
}

fn linux_id(name: &str, group: bool) -> &str {
    match name {
        "root" | "system" => "root",
        "graphics" | "camera" | "media" if group => "video",
        "radio" if group => "dialout",
        "bluetooth" => "bluetooth",
        name if name.starts_with("net_bt") => "bluetooth",
        "audio" | "input" | "nobody" => name,
        "shell" => "root",
        _ => "root",
    }
}

fn safe_path(path: &str) -> bool {
    path.starts_with("/dev/")
        && path.len() > 5
        && !path.contains("..")
        && path
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "/_-.[]*?!".contains(c))
}

fn merge(rules: &mut BTreeMap<String, NodeRule>, incoming: NodeRule) {
    if let Some(rule) = rules.get_mut(&incoming.path) {
        if incoming.mode.is_some() {
            rule.mode = incoming.mode;
        }
        if incoming.owner.is_some() {
            rule.owner = incoming.owner;
            rule.android_owner = incoming.android_owner;
        }
        if incoming.group.is_some() {
            rule.group = incoming.group;
            rule.android_group = incoming.android_group;
        }
        rule.sources.extend(incoming.sources);
        rule.sources.sort();
        rule.sources.dedup();
    } else {
        rules.insert(incoming.path.clone(), incoming);
    }
}

pub fn parse_rc(source: &str, text: &str) -> (Vec<NodeRule>, Vec<String>) {
    let mut rules = BTreeMap::new();
    let mut skipped = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let fields: Vec<_> = line
            .split('#')
            .next()
            .unwrap_or("")
            .split_whitespace()
            .collect();
        let (path, mode, owner, group) = match fields.as_slice() {
            [path, mode, owner, group] if path.starts_with("/dev/") => {
                (*path, Some(*mode), Some(*owner), Some(*group))
            }
            ["chmod", mode, path] if path.starts_with("/dev/") => (*path, Some(*mode), None, None),
            ["chown", owner, group, path] if path.starts_with("/dev/") => {
                (*path, None, Some(*owner), Some(*group))
            }
            _ => {
                if fields.first().is_some_and(|s| s.starts_with("/dev/"))
                    || (fields
                        .first()
                        .is_some_and(|s| ["chmod", "chown"].contains(s))
                        && fields.iter().any(|s| s.contains("/dev/")))
                {
                    skipped.push(format!("{source}:{}: {}", index + 1, line.trim()));
                }
                continue;
            }
        };
        let valid_mode = mode.is_none_or(|m| {
            (3..=4).contains(&m.len()) && m.bytes().all(|b| (b'0'..=b'7').contains(&b))
        });
        let valid_id =
            |id: &str| !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        if !safe_path(path)
            || !valid_mode
            || !owner.is_none_or(valid_id)
            || !group.is_none_or(valid_id)
        {
            skipped.push(format!("{source}:{}: {}", index + 1, line.trim()));
            continue;
        }
        merge(
            &mut rules,
            NodeRule {
                path: path.into(),
                mode: mode.map(|m| format!("{:04o}", u16::from_str_radix(m, 8).unwrap())),
                owner: owner.map(|id| linux_id(id, false).into()),
                group: group.map(|id| linux_id(id, true).into()),
                android_owner: owner.map(str::to_owned),
                android_group: group.map(str::to_owned),
                sources: vec![source.into()],
            },
        );
    }
    (rules.into_values().collect(), skipped)
}

pub fn render_udev(rules: &[NodeRule]) -> String {
    let sources: BTreeSet<_> = rules
        .iter()
        .flat_map(|r| r.sources.iter().map(String::as_str))
        .collect();
    let mut text = format!(
        "# Generated by loaphone\n# Sources: {}\n",
        sources.into_iter().collect::<Vec<_>>().join(", ")
    );
    let mut sorted: Vec<_> = rules.iter().collect();
    sorted.sort_by(|a, b| a.path.cmp(&b.path));
    for rule in sorted {
        if rule.android_owner.is_some() || rule.android_group.is_some() {
            text.push_str(&format!(
                "# Android user={} group={}\n",
                rule.android_owner.as_deref().unwrap_or("-"),
                rule.android_group.as_deref().unwrap_or("-")
            ));
        }
        text.push_str(&format!("ENV{{DEVNAME}}==\"{}\"", rule.path));
        for (key, value) in [
            ("OWNER", &rule.owner),
            ("GROUP", &rule.group),
            ("MODE", &rule.mode),
        ] {
            if let Some(value) = value {
                text.push_str(&format!(", {key}=\"{value}\""));
            }
        }
        text.push('\n');
    }
    text
}

pub fn build_overlay_at(w: &Path) -> Result<OverlayReport, String> {
    let mut files = Vec::new();
    let dump = w.join("dump/init-root.txt");
    if dump.is_file() {
        files.push(dump);
    }
    let vendor_ueventd = w.join("dump/ueventd.rc");
    if vendor_ueventd.is_file() {
        files.push(vendor_ueventd);
    }
    let vendor_init = w.join("dump/init");
    if vendor_init.is_dir() {
        let mut init_files = Vec::new();
        for entry in walkdir::WalkDir::new(vendor_init) {
            let entry = entry.map_err(|e| e.to_string())?;
            if entry.file_type().is_file() && entry.path().extension().is_some_and(|s| s == "rc") {
                init_files.push(entry.into_path());
            }
        }
        init_files.sort();
        files.extend(init_files);
    }
    let blobs = w.join("blobs");
    if blobs.exists() {
        let mut rc_files = Vec::new();
        for entry in walkdir::WalkDir::new(&blobs).sort_by_file_name() {
            let entry = entry.map_err(|e| e.to_string())?;
            let name = entry.file_name().to_string_lossy();
            let in_init = entry.path().ancestors().any(|p| {
                p.file_name().is_some_and(|s| s == "init")
                    && p.parent()
                        .and_then(Path::file_name)
                        .is_some_and(|s| s == "etc")
            });
            if entry.file_type().is_file()
                && name.ends_with(".rc")
                && (name.starts_with("ueventd") || name.starts_with("init") || in_init)
            {
                rc_files.push(entry.into_path());
            }
        }
        rc_files.sort();
        files.extend(rc_files);
    }
    if files.is_empty() {
        return Err("No rc sources found: collect a hardware dump or import init/ueventd rc files into blobs.".into());
    }
    let mut merged = BTreeMap::new();
    let mut skipped = Vec::new();
    let mut sources = Vec::new();
    for file in files {
        let source = file
            .strip_prefix(w)
            .map_err(|e| e.to_string())?
            .to_string_lossy()
            .into_owned();
        let text = fs::read_to_string(&file).map_err(|e| format!("{}: {e}", file.display()))?;
        let (rules, ignored) = parse_rc(&source, &text);
        for rule in rules {
            merge(&mut merged, rule);
        }
        skipped.extend(ignored);
        sources.push(source);
    }
    let rules: Vec<_> = merged.into_values().collect();
    let mut rules_text = render_udev(&rules);
    // Include sources with no device-node entries as well.
    let header_end = rules_text.find("\n").unwrap() + 1;
    let sources_end = rules_text[header_end..].find("\n").unwrap() + header_end;
    rules_text.replace_range(
        header_end..sources_end,
        &format!("# Sources: {}", sources.join(", ")),
    );
    let overlay = w.join("overlay");
    if overlay.exists() {
        fs::remove_dir_all(&overlay).map_err(|e| e.to_string())?;
    }
    let rules_dir = overlay.join("etc/udev/rules.d");
    fs::create_dir_all(&rules_dir).map_err(|e| e.to_string())?;
    fs::write(rules_dir.join("99-loaphone-android.rules"), &rules_text)
        .map_err(|e| e.to_string())?;
    let (firmware_count, firmware_skipped) =
        copy_overlay_firmware(&blobs, &overlay.join("lib/firmware"))?;
    skipped.extend(firmware_skipped);
    let zip_path = w.join("overlay.zip");
    let mut zip = zip::ZipWriter::new(fs::File::create(&zip_path).map_err(|e| e.to_string())?);
    for entry in walkdir::WalkDir::new(&overlay).sort_by_file_name() {
        let entry = entry.map_err(|e| e.to_string())?;
        if !entry.file_type().is_file() {
            continue;
        }
        let name = entry
            .path()
            .strip_prefix(&overlay)
            .map_err(|e| e.to_string())?
            .to_string_lossy()
            .replace('\\', "/");
        zip.start_file(
            name,
            zip::write::SimpleFileOptions::default()
                .compression_method(zip::CompressionMethod::Deflated)
                .unix_permissions(0o644),
        )
        .map_err(|e| e.to_string())?;
        std::io::copy(
            &mut fs::File::open(entry.path()).map_err(|e| e.to_string())?,
            &mut zip,
        )
        .map_err(|e| e.to_string())?;
    }
    zip.finish().map_err(|e| e.to_string())?;
    Ok(OverlayReport {
        rules,
        rules_text,
        sources,
        skipped,
        firmware_count,
        overlay_dir: overlay.display().to_string(),
        zip_path: zip_path.display().to_string(),
    })
}

#[tauri::command]
pub async fn build_overlay(
    app: tauri::AppHandle,
    codename: String,
) -> Result<OverlayReport, String> {
    tauri::async_runtime::spawn_blocking(move || build_overlay_at(&workspace(&app, &codename)?))
        .await
        .map_err(|e| e.to_string())?
}

#[cfg(test)]
mod tests {
    use super::*;
    const UEVENTD: &str = include_str!("../tests/fixtures/ueventd.qcom.rc");
    const INIT: &str = include_str!("../tests/fixtures/init.qcom.rc");

    #[test]
    fn real_device_rules() {
        let (rules, skipped) = parse_rc("ueventd.qcom.rc", UEVENTD);
        assert!(skipped.is_empty());
        let node = |path: &str| rules.iter().find(|r| r.path == path).unwrap();
        assert_eq!(node("/dev/kgsl-3d0").mode.as_deref(), Some("0666"));
        assert_eq!(node("/dev/ion").mode.as_deref(), Some("0664"));
        assert_eq!(node("/dev/smd11").group.as_deref(), Some("dialout"));
        assert_eq!(node("/dev/smd11").owner.as_deref(), Some("root"));
        assert_eq!(node("/dev/smd7").group.as_deref(), Some("bluetooth"));
        assert!(rules.iter().all(|r| !r.path.starts_with("/sys")));
        let (init, skipped) = parse_rc("init.qcom.rc", INIT);
        assert!(skipped.is_empty());
        assert_eq!(
            init.iter()
                .find(|r| r.path == "/dev/dash")
                .unwrap()
                .mode
                .as_deref(),
            Some("0666")
        );
    }

    #[test]
    fn overrides_safety_and_rendering() {
        let text = "/dev/gpu* 0600 system system\non boot\n chown camera graphics /dev/gpu*\n chmod 666 /dev/gpu*\n/dev/unknown 0600 mystery unknown\n/dev/${node} 0666 root root\n/dev/bad 0888 root root\nchmod 0666 /dev/evil\"\n/sys/foo attr 0666 root root\nsubsystem input\n devname uevent_devname\n dirname input";
        let (rules, skipped) = parse_rc("test.rc", text);
        assert_eq!(skipped.len(), 3);
        assert_eq!(rules.len(), 2);
        assert_eq!(rules[0].android_owner.as_deref(), Some("camera"));
        assert_eq!(rules[0].owner.as_deref(), Some("root"));
        assert_eq!(rules[0].group.as_deref(), Some("video"));
        assert_eq!(rules[1].group.as_deref(), Some("root"));
        let rendered = render_udev(&rules);
        assert!(rendered.contains("# Android user=camera group=graphics\nENV{DEVNAME}==\"/dev/gpu*\", OWNER=\"root\", GROUP=\"video\", MODE=\"0666\"\n"));
        assert!(
            rendered
                .lines()
                .filter(|line| !line.starts_with('#'))
                .all(|line| !line.contains('#'))
        );
        assert!(rendered.contains("# Android user=mystery group=unknown"));
        assert!(parse_rc("empty", "# comment\n\n").0.is_empty());
        assert_eq!(render_udev(&[]), "# Generated by loaphone\n# Sources: \n");
        for name in ["graphics", "camera", "media"] {
            assert_eq!(linux_id(name, true), "video");
        }
        assert_eq!(linux_id("input", true), "input");
        assert_eq!(linux_id("audio", true), "audio");
        assert_eq!(linux_id("net_bt_custom", true), "bluetooth");
        assert_eq!(
            parse_rc("bad", "chmod 0666 /dev/\"broken\npath\"").1.len(),
            1
        );
    }

    #[test]
    fn vendor_dump_sources_and_precedence() {
        let w = std::env::temp_dir().join(format!("loaphone-vendor-dump-{}", std::process::id()));
        fs::create_dir_all(w.join("dump/init/nested")).unwrap();
        fs::write(w.join("dump/ueventd.rc"), "/dev/gpu 0600 system system").unwrap();
        let vendor_only = build_overlay_at(&w).unwrap();
        assert_eq!(vendor_only.sources, ["dump/ueventd.rc"]);
        assert_eq!(vendor_only.rules[0].mode.as_deref(), Some("0600"));
        fs::write(w.join("dump/init/a.rc"), "chmod 0640 /dev/gpu").unwrap();
        fs::write(w.join("dump/init/nested/z.rc"), "chmod 0660 /dev/gpu").unwrap();
        fs::write(w.join("dump/init/ignored.txt"), "chmod 0777 /dev/gpu").unwrap();
        fs::write(w.join("dump/init-root.txt"), "/dev/gpu 0666 root root").unwrap();
        let dump = build_overlay_at(&w).unwrap();
        assert_eq!(
            dump.sources,
            [
                "dump/init-root.txt",
                "dump/ueventd.rc",
                "dump/init/a.rc",
                "dump/init/nested/z.rc"
            ]
        );
        assert_eq!(dump.rules[0].mode.as_deref(), Some("0660"));
        assert_eq!(dump.rules[0].android_owner.as_deref(), Some("system"));
        fs::create_dir_all(w.join("blobs/vendor/etc/init")).unwrap();
        fs::write(
            w.join("blobs/vendor/etc/init/device.rc"),
            "chown root graphics /dev/gpu",
        )
        .unwrap();
        let blobs = build_overlay_at(&w).unwrap();
        assert_eq!(blobs.rules[0].group.as_deref(), Some("video"));
        assert_eq!(blobs.rules[0].mode.as_deref(), Some("0660"));
        assert_eq!(blobs.rules[0].sources.len(), 5);
        fs::remove_file(w.join("dump/init-root.txt")).unwrap();
        fs::remove_file(w.join("dump/ueventd.rc")).unwrap();
        fs::remove_dir_all(w.join("blobs")).unwrap();
        let init_only = build_overlay_at(&w).unwrap();
        assert_eq!(init_only.rules[0].mode.as_deref(), Some("0660"));
        assert_eq!(init_only.sources.len(), 2);
        fs::remove_dir_all(w).unwrap();
    }

    #[test]
    fn firmware_layout_and_collisions() {
        let w = std::env::temp_dir().join(format!("loaphone-firmware-{}", std::process::id()));
        let blobs = w.join("blobs");
        for (name, data) in [
            ("odm/firmware/modem.mdt", "first"),
            ("vendor/firmware/modem.mdt", "second"),
            ("vendor/firmware/qcom/a660_zap.b00", "zap"),
            ("firmware_mnt/image/qcom/radio.mbn", "radio"),
            ("vendor/firmware/old/firmware/nested.bin", "nested"),
        ] {
            let file = blobs.join(name);
            fs::create_dir_all(file.parent().unwrap()).unwrap();
            fs::write(file, data).unwrap();
        }
        let dest = w.join("overlay/lib/firmware");
        let (count, skipped) = copy_overlay_firmware(&blobs, &dest).unwrap();
        assert_eq!(count, 4);
        assert_eq!(skipped.len(), 1);
        assert!(skipped[0].contains("vendor/firmware/modem.mdt skipped"));
        assert!(skipped[0].contains("odm/firmware/modem.mdt already supplies modem.mdt"));
        assert_eq!(fs::read_to_string(dest.join("modem.mdt")).unwrap(), "first");
        for name in ["qcom/a660_zap.b00", "qcom/radio.mbn", "nested.bin"] {
            assert!(dest.join(name).is_file());
        }
        assert_eq!(
            crate::rea::copy_firmware(&blobs, &w.join("carved")).unwrap(),
            5
        );
        assert!(w.join("carved/vendor/firmware/modem.mdt").is_file());
        assert!(w.join("carved/firmware_mnt/image/qcom/radio.mbn").is_file());
        fs::remove_dir_all(w).unwrap();
    }

    #[test]
    fn builds_and_rebuilds_overlay() {
        let w = std::env::temp_dir().join(format!("loaphone-overlay-{}", std::process::id()));
        fs::create_dir_all(&w).unwrap();
        assert!(build_overlay_at(&w).unwrap_err().contains("No rc sources"));
        fs::create_dir_all(w.join("dump")).unwrap();
        fs::create_dir_all(w.join("blobs/vendor/etc/init")).unwrap();
        fs::create_dir_all(w.join("blobs/vendor/firmware")).unwrap();
        fs::write(w.join("dump/init-root.txt"), UEVENTD).unwrap();
        fs::write(
            w.join("blobs/vendor/etc/init/device.rc"),
            format!(
                "{INIT}\non boot\n chown system graphics /dev/kgsl-3d0\n chmod 0600 /dev/kgsl-3d0"
            ),
        )
        .unwrap();
        fs::write(w.join("blobs/vendor/firmware/modem.mdt"), b"firmware").unwrap();
        fs::write(w.join("blobs/vendor/firmware/not-firmware.txt"), b"ignored").unwrap();
        let report = build_overlay_at(&w).unwrap();
        assert_eq!(report.firmware_count, 1);
        assert_eq!(report.sources.len(), 2);
        let gpu = report
            .rules
            .iter()
            .find(|r| r.path == "/dev/kgsl-3d0")
            .unwrap();
        assert_eq!(gpu.mode.as_deref(), Some("0600"));
        assert_eq!(gpu.group.as_deref(), Some("video"));
        assert_eq!(gpu.sources.len(), 2);
        assert_eq!(
            fs::read_to_string(w.join("overlay/etc/udev/rules.d/99-loaphone-android.rules"))
                .unwrap(),
            report.rules_text
        );
        let mut zip = zip::ZipArchive::new(fs::File::open(&report.zip_path).unwrap()).unwrap();
        assert_eq!(zip.len(), 2);
        let mut bytes = Vec::new();
        std::io::Read::read_to_end(
            &mut zip.by_name("lib/firmware/modem.mdt").unwrap(),
            &mut bytes,
        )
        .unwrap();
        assert_eq!(bytes, b"firmware");
        fs::write(w.join("overlay/stale"), "stale").unwrap();
        fs::remove_file(w.join("blobs/vendor/firmware/modem.mdt")).unwrap();
        let rebuilt = build_overlay_at(&w).unwrap();
        assert_eq!(rebuilt.firmware_count, 0);
        assert!(!w.join("overlay/stale").exists());
        assert!(!w.join("overlay/lib/firmware/modem.mdt").exists());
        fs::write(w.join("blobs/vendor/etc/init/device.rc"), [0xff]).unwrap();
        assert!(build_overlay_at(&w).is_err());
        fs::remove_dir_all(w).unwrap();
    }
}
